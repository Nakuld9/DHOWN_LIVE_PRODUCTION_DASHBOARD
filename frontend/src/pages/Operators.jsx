function AttendanceTab() {
  const [date, setDate] = useState(new Date().toISOString().slice(0, 10));
  const [shift, setShift] = useState("");
  const [records, setRecords] = useState([]);
  const [loading, setLoading] = useState(true);
  const [workers, setWorkers] = useState([]);
  const [markOp, setMarkOp] = useState("");
  const [markShift, setMarkShift] = useState("D");
  const [markMsg, setMarkMsg] = useState("");

  const load = useCallback(async () => {
    setLoading(true);
    try {
      const p = new URLSearchParams({ date });
      if (shift) p.set("shift", shift);
      const r = await fetch(`/api/attendance?${p}`);
      setRecords(await r.json());
    } catch {}
    finally { setLoading(false); }
  }, [date, shift]);

  useEffect(() => { load(); }, [load]);

  useEffect(() => {
    fetch("/api/operators").then(r => r.json()).then(setWorkers).catch(() => {});
  }, []);

  const markPresent = async () => {
    if (!markOp) { setMarkMsg("Select a worker first."); return; }
    try {
      const res = await fetch("/api/attendance", {
        method: "POST",
        headers: { "Content-Type": "application/json" },
        body: JSON.stringify({ operator_id: markOp, work_date: date, shift: markShift }),
      });
      if (!res.ok) throw new Error((await res.json()).error || "Failed");
      setMarkMsg("Marked present.");
      setMarkOp("");
      load();
    } catch (e) { setMarkMsg("Failed: " + e.message); }
  };

  const removeRecord = async (id) => {
    try {
      const res = await fetch(`/api/attendance/${id}`, { method: "DELETE" });
      if (!res.ok) throw new Error((await res.json()).error || "Failed");
      load();
    } catch (e) { setMarkMsg("Remove failed: " + e.message); }
  };

  const th = { padding: "10px 8px", textAlign: "left", color: "var(--yellow)", fontSize: "13px", borderBottom: "2px solid var(--surface)" };
  const td = { padding: "10px 8px", borderBottom: "1px solid rgba(22,52,93,0.4)", fontSize: "14px" };

  const present = records.length;
  const dayShift = records.filter(r => r.shift === "D").length;
  const nightShift = records.filter(r => r.shift === "N").length;

  return (
    <div>
      {/* KPI */}
      <div style={{ display: "grid", gridTemplateColumns: "repeat(3,1fr)", gap: "14px", marginBottom: "20px" }}>
        {[
          { label: "Present Today", value: present, color: "var(--green)" },
          { label: "Day Shift (D)", value: dayShift, color: "var(--gold-2)" },
          { label: "Night Shift (N)", value: nightShift, color: "var(--purple)" },
        ].map(k => (
          <div key={k.label} style={{ background: "var(--bg)", border: "1px solid var(--border)", borderRadius: "10px", padding: "16px", textAlign: "center" }}>
            <div style={{ fontSize: "28px", fontWeight: "bold", color: k.color }}>{k.value}</div>
            <div style={{ fontSize: "12px", color: "var(--muted)", marginTop: "4px" }}>{k.label}</div>
          </div>
        ))}
      </div>

      {/* Manual mark-present — for staff without RFID cards (supervisors, helpers, drivers, masters) */}
      <div style={{ background: "var(--bg)", border: "1px solid var(--border)", borderRadius: "10px", padding: "16px", marginBottom: "18px" }}>
        <div style={{ color: "var(--yellow)", fontWeight: "bold", fontSize: "14px", marginBottom: "10px" }}>
          Mark Present (no RFID card)
        </div>
        <div style={{ display: "flex", gap: "12px", flexWrap: "wrap", alignItems: "center" }}>
          <select value={markOp} onChange={e => { setMarkOp(e.target.value); setMarkMsg(""); }}
            style={{ padding: "9px 10px", background: "var(--surface)", color: "white", border: "1px solid var(--border)", borderRadius: "6px", fontSize: "14px", minWidth: "260px" }}>
            <option value="">Select worker…</option>
            {workers.map(w => (
              <option key={w.operator_id} value={w.operator_id}>
                {w.operator_name} — {w.worker_type || "OPERATOR"} ({w.operator_code}){w.rfid_tag ? "" : " · no RFID"}
              </option>
            ))}
          </select>
          <select value={markShift} onChange={e => setMarkShift(e.target.value)}
            style={{ padding: "9px 10px", background: "var(--surface)", color: "white", border: "1px solid var(--border)", borderRadius: "6px", fontSize: "14px" }}>
            <option value="D">Day (D)</option>
            <option value="N">Night (N)</option>
          </select>
          <button onClick={markPresent}
            style={{ background: "var(--green)", color: "black", border: "none", padding: "9px 20px", borderRadius: "6px", fontWeight: "bold", cursor: "pointer", fontSize: "14px" }}>
            ✓ Mark Present
          </button>
          {markMsg && <span style={{ color: markMsg.startsWith("Failed") || markMsg.startsWith("Remove") || markMsg.startsWith("Select") ? "var(--crit)" : "var(--green)", fontSize: "13px" }}>{markMsg}</span>}
        </div>
        <div style={{ color: "var(--muted)", fontSize: "12px", marginTop: "8px" }}>
          Marks the selected worker present for <b>{date}</b>. Operators with RFID are also recorded automatically on scan.
        </div>
      </div>

      {/* Filters */}
      <div style={{ display: "flex", gap: "12px", marginBottom: "16px", flexWrap: "wrap" }}>
        <input type="date" value={date} onChange={e => setDate(e.target.value)}
          style={{ padding: "8px 10px", background: "var(--surface)", color: "white", border: "1px solid var(--border)", borderRadius: "6px", fontSize: "14px" }} />
        <select value={shift} onChange={e => setShift(e.target.value)}
          style={{ padding: "8px 10px", background: "var(--surface)", color: "white", border: "1px solid var(--border)", borderRadius: "6px", fontSize: "14px" }}>
          <option value="">All Shifts</option>
          <option value="D">Day (D)</option>
          <option value="N">Night (N)</option>
        </select>
        <button onClick={load} style={{ background: "var(--yellow)", color: "black", border: "none", padding: "8px 18px", borderRadius: "6px", fontWeight: "bold", cursor: "pointer", fontSize: "14px" }}>
          Refresh
        </button>
      </div>

      {/* Table */}
      <div style={{ background: "var(--surface)", border: "1px solid var(--border)", borderRadius: "12px", overflowX: "auto" }}>
        <table width="100%" style={{ borderCollapse: "collapse", minWidth: "700px" }}>
          <thead>
            <tr>
              {["Operator", "Shift", "Clock In", "Last Seen", "Scans", "Status", "Actions"].map(h => (
                <th key={h} style={th}>{h}</th>
              ))}
            </tr>
          </thead>
          <tbody>
            {loading && <tr><td colSpan="7" style={{ padding: "24px", textAlign: "center", color: "var(--muted)" }}>Loading...</td></tr>}
            {!loading && records.length === 0 && (
              <tr><td colSpan="7" style={{ padding: "24px", textAlign: "center", color: "var(--muted)", fontStyle: "italic" }}>
                No attendance records for {date}{shift ? ` (${shift === "D" ? "Day" : "Night"} shift)` : ""}. Use “Mark Present” above for staff without RFID; operators with RFID are recorded automatically on scan.
              </td></tr>
            )}
            {records.map(r => (
              <tr key={r.attendance_id}>
                <td style={{ ...td, fontWeight: "bold", color: "var(--yellow)" }}>{r.operator_name}</td>
                <td style={td}>
                  <span style={{ background: r.shift === "D" ? "rgba(251,191,36,0.2)" : "rgba(129,140,248,0.2)", color: r.shift === "D" ? "var(--gold-2)" : "var(--purple)", padding: "2px 10px", borderRadius: "4px", fontSize: "13px", fontWeight: "bold" }}>
                    {r.shift === "D" ? "☀ Day" : "🌙 Night"}
                  </span>
                </td>
                <td style={{ ...td, color: "var(--green)" }}>{r.clock_in ? new Date(r.clock_in).toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit", hour12: true }) : "—"}</td>
                <td style={{ ...td, color: "var(--muted)" }}>{r.last_seen ? new Date(r.last_seen).toLocaleTimeString("en-IN", { hour: "2-digit", minute: "2-digit", hour12: true }) : "—"}</td>
                <td style={{ ...td, color: "var(--link)" }}>{r.scan_count}</td>
                <td style={td}>
                  <span style={{ background: "rgba(34,197,94,0.15)", color: "var(--green)", padding: "2px 10px", borderRadius: "4px", fontSize: "13px", fontWeight: "bold" }}>
                    {r.status}
                  </span>
                </td>
                <td style={td}>
                  <button onClick={() => removeRecord(r.attendance_id)}
                    style={{ background: "transparent", color: "var(--crit)", border: "1px solid var(--crit)", padding: "4px 12px", borderRadius: "5px", cursor: "pointer", fontSize: "13px", fontWeight: "bold" }}>
                    Remove
                  </button>
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}

export default Operators;
