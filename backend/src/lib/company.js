// The firm's display identity, read from app_settings.
//
// app_settings already holds company_name, factory_address, gst_number and the
// rest — one row set per database, so it is already per firm and already
// editable in the UI. This is the accessor for code that needs those values
// (report letterheads, AI prompts, PDF footers) so they come from the same place
// the Settings screen writes to.
//
// config/tenant.js remains the source for INFRASTRUCTURE — backup directory,
// trusted origins, QR base — because those cannot come from the database the
// application is trying to reach, and differ per deployment rather than per firm.

const pool = require('../../config/database');
const tenant = require('../../config/tenant');

// Cached because a report footer should not cost a query per page. Short TTL so
// an edit in Settings shows up without a restart.
const TTL_MS = 60_000;
let cache = null;
let cachedAt = 0;

async function load() {
  const r = await pool.query(
    `SELECT key, value FROM app_settings
      WHERE key IN ('company_name','factory_address','gst_number','phone_number',
                    'email','website','report_footer')`);
  const m = Object.fromEntries(r.rows.map(x => [x.key, x.value]));
  return {
    // Falls back to tenant config, then to a name rather than an empty
    // letterhead — a report with no company on it is worse than a stale one.
    name:     m.company_name   || tenant.name,
    address:  m.factory_address || tenant.address || '',
    gstin:    m.gst_number     || tenant.gstin || '',
    phone:    m.phone_number   || '',
    email:    m.email          || '',
    website:  m.website        || '',
    footer:   m.report_footer  || `Generated by ${tenant.shortName} MES`,
  };
}

// Returns the cached identity, refreshing when stale. Never throws: if the
// database is unreachable the caller still gets usable values from config, which
// matters because this is on the path of every printed document.
async function company() {
  const now = Date.now();
  if (cache && now - cachedAt < TTL_MS) return cache;
  try {
    cache = await load();
    cachedAt = now;
  } catch (e) {
    if (!cache) {
      cache = { name: tenant.name, address: tenant.address || '', gstin: tenant.gstin || '',
                phone: '', email: '', website: '', footer: `Generated by ${tenant.shortName} MES` };
      cachedAt = now;
    }
    console.error('[company] falling back to config:', e.message);
  }
  return cache;
}

// Called after Settings are saved so the change is visible immediately.
const invalidate = () => { cache = null; cachedAt = 0; };

module.exports = { company, invalidate };
